export function IconChevron({
  className,
  direction = "down",
}: {
  className?: string;
  direction?: "down" | "up" | "left" | "right";
}) {
  const rotation =
    direction === "up"
      ? "rotate(180)"
      : direction === "left"
        ? "rotate(90)"
        : direction === "right"
          ? "rotate(-90)"
          : undefined;
  return (
    <svg
      className={className}
      width="16"
      height="16"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      style={rotation ? { transform: rotation } : undefined}
    >
      <path d="m6 9 6 6 6-6" />
    </svg>
  );
}

